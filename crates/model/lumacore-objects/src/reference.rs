//! The command and object reference (`docs/user/reference/`), generated from
//! the registries (decisions §29): what every word is, takes, needs and
//! touches. `gen-docs` writes it; `the_reference_is_current` (`tests/catalog`, on the
//! whole catalog, §34 25.15) fails until the committed files match what the registries make.

use std::fmt::Write;
use std::path::{Path, PathBuf};

use crate::commands::registry::{CommandDef, Doc, Reach, Status, Undo};
use crate::objects::ObjectDef;

/// Where the reference lives in the repo.
pub fn reference_dir(root: &Path) -> PathBuf {
    root.join("docs/user/reference")
}

const HEADER: &str = "<!-- Generated by `cargo run -p lumacore-station --bin gen-docs` from the registries \
(crates/model/lumacore-objects/src/commands/registry.rs, core/objects/). Do not edit: change the CommandDef / \
ObjectDef and regenerate. -->\n\n";

/// `commands.md`: every command, by help category.
pub fn commands() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Command reference\n\n");
    out.push_str(
        "Every command word, generated from the command registry. Objects (`Fixture`, `Group`, …) \
         and their verbs are in [objects.md](objects.md); the language itself is in \
         [../syntax/lum.md](../syntax/lum.md).\n\n\
         Columns: **rights** = the level needed (Guest < Playback < Presets < Program < Setup < \
         Admin; a line naming an object takes the object's level for the verb, see \
         [objects.md](objects.md)) · **scope** = where it runs in a LumaSession \
         (Master: on the master as you; Station: here; Client: in your shell) · **reach** = what \
         it touches besides the show (TreeShell, Drive) · **undo** = how Oops treats it.\n\n",
    );
    let _ = writeln!(
        out,
        "Options are bare `/words` (a quoted `\"/word\"` is a value). Each word lists its own; \
         these go on every line: {}. Any other `/word` is refused (E-CMD-018).\n",
        crate::commands::flags::globals_line().replace('<', "‹").replace('>', "›")
    );
    let mut cats: Vec<&'static str> = crate::commands::registry::all().map(|c| c.doc.category.label()).collect();
    cats.sort_unstable();
    cats.dedup();
    out.push_str("| Category | Commands |\n|---|---|\n");
    for cat in &cats {
        let words: Vec<String> = sorted(crate::commands::registry::all().filter(|c| c.doc.category.label() == *cat))
            .iter()
            .map(|c| format!("[{}](#{})", c.label(), anchor(c.label())))
            .collect();
        let _ = writeln!(out, "| {cat} | {} |", words.join(" · "));
    }
    for cat in &cats {
        let _ = write!(out, "\n## {cat}\n");
        for cmd in sorted(crate::commands::registry::all().filter(|c| c.doc.category.label() == *cat)) {
            command(&mut out, cmd);
        }
    }
    out
}

fn sorted<'a>(it: impl Iterator<Item = &'a CommandDef>) -> Vec<&'a CommandDef> {
    let mut v: Vec<&CommandDef> = it.collect();
    v.sort_by_key(|c| c.label().to_ascii_lowercase());
    v
}

fn command(out: &mut String, c: &CommandDef) {
    let _ = write!(out, "\n### {}\n\n", c.label());
    let mut facts = vec![
        format!(
            "rights {}{}",
            c.rights.label(),
            if c.arg_rights.is_some() { " (some arguments need more)" } else { "" }
        ),
        format!("scope {:?}", c.scope),
        format!("reach {:?}", c.reach),
        format!("undo {}", undo(c.undo)),
    ];
    if !c.aliases.is_empty() {
        facts.insert(0, format!("aliases {}", c.aliases.iter().map(|a| format!("`{a}`")).collect::<Vec<_>>().join(", ")));
    }
    if c.status == Status::Planned {
        facts.insert(0, "**planned — not built yet**".to_string());
    }
    if c.doc.hidden {
        facts.push("hidden from Help".to_string());
    }
    if let Some(v) = c.object_verb {
        facts.push(format!("object verb {v:?}"));
    }
    let _ = writeln!(out, "{}\n", facts.join(" · "));
    doc(out, &c.doc);
    options(out, c.flags);
}

/// A word's declared flags (decisions §31) as a list.
fn options(out: &mut String, flags: &[crate::commands::flags::FlagDef]) {
    if flags.is_empty() {
        return;
    }
    out.push_str("Options:\n\n");
    for f in flags {
        let verbs = f.verbs_label();
        let verbs = if verbs.is_empty() { String::new() } else { format!(" ({verbs})") };
        let _ = writeln!(out, "- `{}`{verbs}: {}", f.usage(), f.doc);
    }
    out.push('\n');
}

fn undo(u: Undo) -> String {
    match u {
        Undo::ReadOnly => "read-only".into(),
        Undo::Untracked => "not undone".into(),
        Undo::Tracked(kind) if kind.main => format!("Oops ({}, Main)", kind.category.label()),
        Undo::Tracked(kind) => format!("Oops ({})", kind.category.label()),
    }
}

fn doc(out: &mut String, d: &Doc) {
    if !d.syntax.is_empty() {
        let _ = writeln!(out, "```\n{}\n```\n", d.syntax);
    }
    let desc = d.description.split_whitespace().collect::<Vec<_>>().join(" ");
    if !desc.is_empty() {
        let _ = writeln!(out, "{desc}\n");
    }
    if !d.examples.is_empty() {
        out.push_str("Examples:\n\n```\n");
        for ex in d.examples {
            let _ = writeln!(out, "{ex}");
        }
        out.push_str("```\n\n");
    }
    if !d.related.is_empty() {
        let _ = writeln!(out, "Related: {}\n", d.related.iter().map(|r| format!("`{r}`")).collect::<Vec<_>>().join(", "));
    }
}

/// `objects.md`: every object, its verbs, tree path and writable properties.
pub fn objects() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Object reference\n\n");
    out.push_str(
        "Every object keyword, generated from the object registry: what you can do to it (its \
         verbs — the command words are in [commands.md](commands.md)), where it lives in the \
         object tree, which properties `Set` may change and the rights level each verb needs \
         (Guest < Playback < Presets < Program < Setup < Admin).\n\n",
    );
    let mut objs: Vec<&ObjectDef> = crate::objects::all().collect::<Vec<_>>();
    objs.sort_by_key(|o| o.keyword.to_ascii_lowercase());
    let index: Vec<String> = objs.iter().map(|o| format!("[{}](#{})", o.keyword, anchor(o.keyword))).collect();
    let _ = writeln!(out, "{}\n", index.join(" · "));
    for o in objs {
        object(&mut out, o);
    }
    out
}

fn object(out: &mut String, o: &ObjectDef) {
    let _ = write!(out, "\n## {}\n\n", o.keyword);
    let mut facts = Vec::new();
    if !o.aliases.is_empty() {
        facts.push(format!("aliases {}", o.aliases.iter().map(|a| format!("`{a}`")).collect::<Vec<_>>().join(", ")));
    }
    let verbs: Vec<String> = o
        .verbs
        .iter()
        .map(|(v, _)| match (o.reach)(*v) {
            Reach::Show => format!("{v:?}"),
            r => format!("{v:?} (reach {r:?})"),
        })
        .collect();
    facts.push(format!("verbs {}", verbs.join(", ")));
    // What it does with no verb (decisions §33 6, 40): `Group 3` = `SelectFixtures Group 3`.
    let ids = if o.lum.counted() { " <ids>" } else { "" };
    facts.push(format!("default verb {0:?} (`{1}{ids}` = `{0:?} {1}{ids}`)", o.default_verb, o.keyword));
    // How it reads a dotted id (lum.md, decisions §12 "Tags hardened"); a whole number says nothing.
    if !matches!(o.lum.reading, crate::objects::IdReading::Whole | crate::objects::IdReading::None) {
        facts.push(format!("ids {}", o.lum.reading_text()));
    }
    if !o.planned.is_empty() {
        let planned: Vec<String> = o.planned.iter().map(|v| format!("{v:?}")).collect();
        facts.push(format!("**planned — not built yet:** {}", planned.join(", ")));
    }
    facts.push(format!("rights {}", crate::rights::describe_object(o)));
    if let Some(tree) = &o.tree {
        facts.push(format!("tree `{}`", tree.node.path()));
    }
    if o.pool.is_some() {
        facts.push("pool window".to_string());
    }
    let _ = writeln!(out, "{}\n", facts.join(" · "));
    doc(out, &o.doc);
    options(out, o.flags);
    // Its properties (decisions §33 58): `Set <target> "<Property>" <value>`.
    if let Some(props) = o.props {
        out.push_str("| Property | Value | Rights | Home | |\n|---|---|---|---|---|\n");
        for p in props.every() {
            let _ = writeln!(
                out,
                "| \"{}\" | {} | {} | {} | {} |",
                p.name,
                crate::commands::set::kind_text(p).replace('|', "/"),
                crate::props::rights_of(o, p).label(),
                p.home.word(),
                p.doc
            );
        }
        out.push('\n');
    }
}

/// GitHub's heading anchor.
fn anchor(heading: &str) -> String {
    heading
        .to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric() || *c == '-' || *c == ' ' || *c == '_')
        .map(|c| if c == ' ' { '-' } else { c })
        .collect()
}
