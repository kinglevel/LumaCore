use super::*;

#[test]
fn a_guarded_panic_returns_its_location_and_message() {
    let report = guarded(|| -> u32 { panic!("boom {}", 7) }).unwrap_err();
    assert!(report.file.ends_with("panic_report/tests.rs"));
    assert_eq!(report.message, "boom 7");
    assert!(report.number > 0);
    assert_eq!(guarded(|| 5).unwrap(), 5);
}
