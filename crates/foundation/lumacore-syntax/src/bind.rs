//! Binding a statement to a verb's signature (decisions §33 4, 7, 8, 17).
//!
//! The parser's tree is generic; which slot is a property, a name or a value, whether `At` is a
//! value or a destination, which options a word takes — that is the verb's [`Signature`]. A
//! handler declares it as a struct (`#[derive(Args)]` in `lumacore-syntax-derive`): the struct is
//! the signature, [`bind`] fills it. Trailing slots bind from the right (decision 17): when the
//! statement has fewer plain values than the signature needs, the last quoted name or number of
//! the target is taken for them (`Set UserProfile "ClearBuffer" On` — your profile, its
//! ClearBuffer).

use crate::ast::*;
use crate::errors::{Diag, codes};
use crate::{Span, Vocabulary};

/// What a verb takes, declared once per verb × object (generated by `#[derive(Args)]`).
#[derive(Debug, Clone, Copy)]
pub struct Signature {
    pub verb: &'static str,
    /// The object the handler is for (`Store Group`); None = the verb's own handler.
    pub object: Option<&'static str>,
    pub target: Need,
    /// The `On` / `Off` after a hold verb.
    pub phase: bool,
    /// Plain slots after the target, in order; they bind from the right.
    pub slots: &'static [SlotDef],
    /// Helper slots (`At 50`, `Fade 2`), in any order.
    pub helpers: &'static [HelperDef],
    pub options: &'static [OptionSig],
    /// Takes an `If` filter (decision 23).
    pub condition: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Need {
    /// No target: bare ids are read as the plain slots (`Redo 3`).
    Never,
    Optional,
    Required,
}

#[derive(Debug, Clone, Copy)]
pub struct SlotDef {
    pub kind: SlotKind,
    pub required: bool,
    /// The struct field, for help and messages.
    pub field: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SlotKind {
    /// A quoted property name (decision 7).
    Property,
    /// Quoted text (Label's name).
    Name,
    /// One value expression.
    Value,
}

#[derive(Debug, Clone, Copy)]
pub struct HelperDef {
    pub word: &'static str,
    /// `At 50` (a value) or `At Output 1` (where to) — never both (decision 8).
    pub role: Role,
    pub required: bool,
    pub field: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Role {
    Value,
    Destination,
}

#[derive(Debug, Clone, Copy)]
pub struct OptionSig {
    pub name: &'static str,
    pub takes_value: bool,
}

/// A statement bound to a signature: every declared part by its index.
#[derive(Debug, Clone, Default)]
pub struct Bound {
    pub target: Option<Target>,
    pub phase: Option<Spanned<Phase>>,
    pub slots: Vec<Option<Value>>,
    pub helpers: Vec<Option<Value>>,
    /// `Some(None)` = a switch given, `Some(Some(v))` = a valued option given.
    pub options: Vec<Option<Option<Value>>>,
    pub condition: Option<Condition>,
    /// Where a missing part would go (the statement's end).
    pub end: Span,
}

/// A verb's typed arguments (`#[derive(Args)]`).
pub trait Args: Sized {
    const SIGNATURE: Signature;
    fn from_bound(bound: Bound, vocab: &Vocabulary) -> Result<Self, Diag>;
}

/// A value slot's field type.
pub trait FromValue: Sized {
    /// Whether the slot must be given (`Option<T>` is not).
    const REQUIRED: bool = true;
    fn from_value(value: Option<Value>, end: Span, vocab: &Vocabulary) -> Result<Self, Diag>;
}

/// A target field's type: `Target` (required) or `Option<Target>`.
pub trait FromTarget: Sized {
    const REQUIRED: bool = true;
    fn from_target(target: Option<Target>, end: Span) -> Result<Self, Diag>;
}

/// The phase field's type: `Phase` (required) or `Option<Phase>`.
pub trait FromPhase: Sized {
    fn from_phase(phase: Option<Spanned<Phase>>, end: Span) -> Result<Self, Diag>;
}

impl FromPhase for Phase {
    fn from_phase(phase: Option<Spanned<Phase>>, end: Span) -> Result<Self, Diag> {
        phase.map(|p| p.node).ok_or(Diag { code: codes::HOLD_PHASE, span: end, message: "On or Off right after the verb".into() })
    }
}

impl FromPhase for Option<Phase> {
    fn from_phase(phase: Option<Spanned<Phase>>, _: Span) -> Result<Self, Diag> {
        Ok(phase.map(|p| p.node))
    }
}

/// Bind a statement to `A`'s signature. `globals` are the options every line takes
/// (`/NoConfirmation`, `/NoOops`, …).
pub fn bind<A: Args>(statement: &Statement, vocab: &Vocabulary, globals: &[&str]) -> Result<A, Diag> {
    let bound = bind_signature(&A::SIGNATURE, statement, vocab, globals)?;
    A::from_bound(bound, vocab)
}

/// The generic half of [`bind`]: the statement's parts placed by the signature.
pub fn bind_signature(sig: &Signature, statement: &Statement, vocab: &Vocabulary, globals: &[&str]) -> Result<Bound, Diag> {
    let end = Span { start: statement.span.end, end: statement.span.end };
    let Body::Lum(lum) = &statement.body else {
        return Err(Diag { code: codes::UNEXPECTED, span: statement.span, message: format!("{} takes a Lum statement", sig.verb) });
    };
    let mut bound = Bound {
        slots: vec![None; sig.slots.len()],
        helpers: vec![None; sig.helpers.len()],
        options: vec![None; sig.options.len()],
        end,
        ..Bound::default()
    };

    if sig.phase {
        bound.phase = lum.phase.clone();
    }
    if let Some(c) = &lum.condition {
        if !sig.condition {
            return Err(Diag { code: codes::UNEXPECTED, span: c.span, message: format!("{} takes no If", sig.verb) });
        }
        bound.condition = Some(c.clone());
    }

    // Helpers by their word, plain values in order.
    let mut plain: Vec<Value> = Vec::new();
    for slot in &lum.slots {
        match slot {
            Slot::Value(v) => plain.push(v.clone()),
            Slot::Helper { word, value } => {
                let name = &vocab.word(word.node).name;
                // A helper word the signature doesn't take, with no value after it, is a value
                // word in a plain slot (decision 64: the slot decides — `Set Screen
                // "EncoderLayer" Fade`).
                if value.is_none() && !sig.helpers.iter().any(|h| h.word.eq_ignore_ascii_case(name)) && !sig.slots.is_empty() {
                    plain.push(Value::Word(word.clone()));
                    continue;
                }
                let Some(i) = sig.helpers.iter().position(|h| h.word.eq_ignore_ascii_case(name)) else {
                    return Err(Diag { code: codes::UNEXPECTED, span: word.span, message: format!("{} takes no {name}", what(sig)) });
                };
                if bound.helpers[i].is_some() {
                    return Err(Diag { code: codes::UNEXPECTED, span: word.span, message: format!("{name} is given twice") });
                }
                let Some(value) = value.clone() else {
                    return Err(Diag { code: codes::MISSING, span: word.span, message: format!("{name} needs a value") });
                };
                if sig.helpers[i].role == Role::Destination && !is_destination(&value) {
                    return Err(Diag {
                        code: codes::VALUE_WORD,
                        span: value.span(),
                        message: format!("{} {name} takes where to: an object or a number", sig.verb),
                    });
                }
                bound.helpers[i] = Some(value);
            }
        }
    }
    for (i, h) in sig.helpers.iter().enumerate() {
        if h.required && bound.helpers[i].is_none() {
            return Err(Diag { code: codes::MISSING, span: end, message: format!("{} needs {} …", what(sig), h.word) });
        }
    }

    // The target, and right-binding of the plain slots (decision 17).
    let mut target = lum.target.clone();
    let required = sig.slots.iter().filter(|s| s.required).count();
    if sig.target == Need::Never {
        if let Some(t) = target.take() {
            let mut front = ids_as_values(&t).ok_or_else(|| Diag {
                code: codes::UNEXPECTED,
                span: t.span(),
                message: format!("{} acts on nothing — no object here", sig.verb),
            })?;
            front.append(&mut plain);
            plain = front;
        }
    } else {
        while plain.len() < required {
            let kind = sig.slots[required - plain.len() - 1].kind;
            match target.as_mut().and_then(|t| take_last_id(t, kind)) {
                Some(v) => plain.insert(0, v),
                None => break,
            }
        }
    }
    if plain.len() > sig.slots.len() {
        let extra = &plain[0];
        return Err(Diag { code: codes::UNEXPECTED, span: extra.span(), message: format!("{} takes nothing more here", what(sig)) });
    }
    if plain.len() < required {
        let missing = sig.slots.iter().filter(|s| s.required).nth(plain.len()).map_or("a value", |s| s.field);
        return Err(Diag { code: codes::MISSING, span: end, message: format!("{} needs {missing}", what(sig)) });
    }
    let mut optional_left = plain.len() - required;
    let mut values = plain.into_iter();
    for (i, s) in sig.slots.iter().enumerate() {
        if s.required || optional_left > 0 {
            if !s.required {
                optional_left -= 1;
            }
            let v = values.next().expect("counted");
            if matches!(s.kind, SlotKind::Property | SlotKind::Name) && !matches!(v, Value::Text(_)) {
                let what = if s.kind == SlotKind::Property { "a quoted property name" } else { "quoted text" };
                return Err(Diag { code: codes::VALUE_WORD, span: v.span(), message: format!("{} takes {what} here", sig.verb) });
            }
            bound.slots[i] = Some(v);
        }
    }
    if sig.target == Need::Required && target.as_ref().is_none_or(|t| t.items.is_empty()) {
        return Err(Diag { code: codes::MISSING, span: end, message: format!("{} needs what it acts on", sig.verb) });
    }
    bound.target = target.filter(|t| !t.items.is_empty());

    // Options: the signature's, else a global one, else refused.
    for o in &lum.options {
        match sig.options.iter().position(|s| s.name.eq_ignore_ascii_case(&o.name.node)) {
            Some(i) => {
                if bound.options[i].is_some() {
                    return Err(Diag { code: codes::UNEXPECTED, span: o.name.span, message: format!("/{} is given twice", o.name.node) });
                }
                bound.options[i] = Some(o.value.clone());
            }
            None if globals.iter().any(|g| g.eq_ignore_ascii_case(&o.name.node)) => {}
            None => {
                return Err(Diag { code: codes::OPTION, span: o.name.span, message: format!("{} has no option /{}", what(sig), o.name.node) });
            }
        }
    }
    Ok(bound)
}

/// `Store Group` / `Redo` — how a message names the line's verb (and object).
fn what(sig: &Signature) -> String {
    match sig.object {
        Some(o) => format!("{} {o}", sig.verb),
        None => sig.verb.to_string(),
    }
}

fn is_destination(v: &Value) -> bool {
    matches!(v, Value::Target(_) | Value::Number(_) | Value::Spread { .. })
}

/// A bare-ids target read as plain values: `Redo 3`, `Unwatch "x"`.
fn ids_as_values(t: &Target) -> Option<Vec<Value>> {
    let [(None, Item::Ids(ids))] = t.items.as_slice() else { return None };
    ids.ranges
        .iter()
        .map(|(op, r)| match (op, r) {
            (None, Range::One(Id::Number(n))) => Some(Value::Number(n.clone())),
            (None, Range::One(Id::Name(n))) => Some(Value::Text(n.clone())),
            (None, Range::Thru { from: Some(Id::Number(a)), to: Some(Id::Number(b)), .. }) => {
                Some(Value::Spread { from: a.clone(), to: b.clone() })
            }
            _ => None,
        })
        .collect()
}

/// The target's last single id, taken off for a trailing slot of `kind` (decision 17): a quoted
/// name for a property or name, a name or number for a value.
fn take_last_id(t: &mut Target, kind: SlotKind) -> Option<Value> {
    let (_, item) = t.items.last_mut()?;
    let ids = match item {
        Item::Path(segments) => segments.last_mut()?.ids.as_mut()?,
        Item::Ids(ids) => ids,
        _ => return None,
    };
    let (op, Range::One(id)) = ids.ranges.last()? else { return None };
    let value = match (op, id, kind) {
        // `Set Show "Autosave" + 10`: the value is one expression (decisions 11, 17) — a spaced
        // `+` / `-` before the last number is relative, not a set operator, when the ids before
        // it are what the value slot leaves.
        (Some(op), Id::Number(n), SlotKind::Value) if ids.ranges.len() > 1 => {
            let c = match op.node {
                SetOp::Plus => '+',
                SetOp::Minus => '-',
            };
            Value::Relative { op: Spanned::new(c, op.span), number: n.clone() }
        }
        (Some(_), ..) if ids.ranges.len() > 1 => return None,
        (_, Id::Name(n), _) => Value::Text(n.clone()),
        (_, Id::Number(n), SlotKind::Value) => Value::Number(n.clone()),
        _ => return None,
    };
    ids.ranges.pop();
    if ids.ranges.is_empty() {
        match item {
            Item::Path(segments) => segments.last_mut().expect("checked").ids = None,
            _ => {
                t.items.pop();
            }
        }
    }
    Some(value)
}

impl Signature {
    /// The signature's own rules, checked when it is compiled (`const _: () = SIG.check();` —
    /// `#[derive(Args)]` writes it): two optional plain slots can't be told apart, a helper or
    /// an option is declared once.
    pub const fn check(&self) {
        let mut i = 0;
        let mut optional = 0;
        while i < self.slots.len() {
            if !self.slots[i].required {
                optional += 1;
            }
            i += 1;
        }
        assert!(optional <= 1, "two optional plain slots can't be told apart");
        let mut a = 0;
        while a < self.helpers.len() {
            let mut b = a + 1;
            while b < self.helpers.len() {
                assert!(!same(self.helpers[a].word, self.helpers[b].word), "a helper is declared twice");
                b += 1;
            }
            a += 1;
        }
        let mut a = 0;
        while a < self.options.len() {
            let mut b = a + 1;
            while b < self.options.len() {
                assert!(!same(self.options[a].name, self.options[b].name), "an option is declared twice");
                b += 1;
            }
            a += 1;
        }
    }

    /// The usage line help shows: `Redo [<steps>]`, `Set <target> "<property>" <value>`.
    pub fn usage(&self) -> String {
        let mut out = vec![self.verb.to_string()];
        if self.phase {
            out.push("On|Off".into());
        }
        if let Some(o) = self.object {
            out.push(o.to_string());
        }
        match self.target {
            Need::Never => {}
            Need::Optional => out.push("[<target>]".into()),
            Need::Required if self.object.is_some() => out.push("<ids>".into()),
            Need::Required => out.push("<target>".into()),
        }
        for s in self.slots {
            let piece = match s.kind {
                SlotKind::Property => format!("\"<{}>\"", s.field),
                SlotKind::Name => format!("\"<{}>\"", s.field),
                SlotKind::Value => format!("<{}>", s.field),
            };
            out.push(if s.required { piece } else { format!("[{piece}]") });
        }
        for h in self.helpers {
            let piece = format!("{} <{}>", h.word, h.field);
            out.push(if h.required { piece } else { format!("[{piece}]") });
        }
        for o in self.options {
            out.push(if o.takes_value { format!("[/{} <value>]", o.name) } else { format!("[/{}]", o.name) });
        }
        out.join(" ")
    }
}

/// ASCII case-insensitive equality, usable in a `const fn`.
const fn same(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if !a[i].eq_ignore_ascii_case(&b[i]) {
            return false;
        }
        i += 1;
    }
    true
}

// ── Field types ──

impl FromTarget for Target {
    fn from_target(target: Option<Target>, end: Span) -> Result<Self, Diag> {
        target.ok_or(Diag { code: codes::MISSING, span: end, message: "needs what it acts on".into() })
    }
}

impl FromTarget for Option<Target> {
    const REQUIRED: bool = false;
    fn from_target(target: Option<Target>, _: Span) -> Result<Self, Diag> {
        Ok(target)
    }
}

impl<T: FromValue> FromValue for Option<T> {
    const REQUIRED: bool = false;
    fn from_value(value: Option<Value>, end: Span, vocab: &Vocabulary) -> Result<Self, Diag> {
        match value {
            None => Ok(None),
            some => T::from_value(some, end, vocab).map(Some),
        }
    }
}

fn missing(end: Span) -> Diag {
    Diag { code: codes::MISSING, span: end, message: "a value is missing".into() }
}

impl FromValue for Value {
    fn from_value(value: Option<Value>, end: Span, _: &Vocabulary) -> Result<Self, Diag> {
        value.ok_or_else(|| missing(end))
    }
}

/// Quoted text.
impl FromValue for String {
    fn from_value(value: Option<Value>, end: Span, _: &Vocabulary) -> Result<Self, Diag> {
        match value.ok_or_else(|| missing(end))? {
            Value::Text(t) => Ok(t.node),
            other => Err(Diag { code: codes::VALUE_WORD, span: other.span(), message: "quoted text here".into() }),
        }
    }
}

/// A command line as a value, written in backticks (decision 91): ``Bind "F5" `List Fixture` ``.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CommandLine(pub String);

impl FromValue for CommandLine {
    fn from_value(value: Option<Value>, end: Span, _: &Vocabulary) -> Result<Self, Diag> {
        match value.ok_or_else(|| missing(end))? {
            Value::Line(l) => Ok(CommandLine(l.node)),
            Value::Text(t) => Err(Diag {
                code: codes::VALUE_WORD,
                span: t.span,
                message: format!("a command line is written in backticks: `{}`", t.node),
            }),
            other => Err(Diag { code: codes::VALUE_WORD, span: other.span(), message: "a command line in backticks here".into() }),
        }
    }
}

/// A whole number (`Redo 3`).
impl FromValue for u32 {
    fn from_value(value: Option<Value>, end: Span, _: &Vocabulary) -> Result<Self, Diag> {
        match value.ok_or_else(|| missing(end))? {
            Value::Number(n) if !n.node.starts_with(['+', '-']) && n.node.parse::<u32>().is_ok() => Ok(n.node.parse().expect("checked")),
            other => Err(Diag { code: codes::VALUE_WORD, span: other.span(), message: "a whole number here".into() }),
        }
    }
}

/// An on / off value: `On` / `Off` / `Yes` / `No` (decision 14).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OnOff(pub bool);

impl FromValue for OnOff {
    fn from_value(value: Option<Value>, end: Span, vocab: &Vocabulary) -> Result<Self, Diag> {
        match switch(value, end, vocab, false)? {
            Switch::On => Ok(OnOff(true)),
            Switch::Off => Ok(OnOff(false)),
            Switch::Toggle => unreachable!("not accepted"),
        }
    }
}

/// An on / off value that also takes `Toggle` (where the property declares it).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Switch {
    On,
    Off,
    Toggle,
}

impl FromValue for Switch {
    fn from_value(value: Option<Value>, end: Span, vocab: &Vocabulary) -> Result<Self, Diag> {
        switch(value, end, vocab, true)
    }
}

fn switch(value: Option<Value>, end: Span, vocab: &Vocabulary, toggle: bool) -> Result<Switch, Diag> {
    let value = value.ok_or_else(|| missing(end))?;
    let accepted = if toggle { "On, Off, Yes, No or Toggle" } else { "On, Off, Yes or No" };
    let refuse = |span| Diag { code: codes::VALUE_WORD, span, message: format!("takes {accepted}") };
    let Value::Word(w) = &value else { return Err(refuse(value.span())) };
    let name = vocab.word(w.node).name.to_ascii_lowercase();
    match name.as_str() {
        "on" | "yes" => Ok(Switch::On),
        "off" | "no" => Ok(Switch::Off),
        "toggle" if toggle => Ok(Switch::Toggle),
        _ => Err(refuse(w.span)),
    }
}

// ── The tree-shell fence (decision 18) ──

/// A fence statement read for its handler: what it names, in order, and its flags.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct FenceLine {
    /// Paths (`..`, `/`, `DataPools.1`, `Root.ShowData`) and quoted text (without quotes), in order.
    pub positional: Vec<String>,
    /// Flags as written without dashes, lowercase, with their value when the flag takes one.
    pub flags: Vec<(String, Option<String>)>,
}

impl FenceLine {
    /// The fence statement's parts; None for any other statement.
    pub fn of(statement: &Statement) -> Option<FenceLine> {
        let Body::Fence { args, .. } = &statement.body else { return None };
        let mut line = FenceLine::default();
        for a in args {
            match a {
                FenceArg::Path(p) => line.positional.push(p.node.clone()),
                FenceArg::Text(t) => line.positional.push(t.node.clone()),
                FenceArg::Flag { name, value, .. } => {
                    line.flags.push((name.node.to_ascii_lowercase(), value.as_ref().map(|v| v.node.clone())))
                }
            }
        }
        Some(line)
    }

    /// The `i`th path or text.
    pub fn arg(&self, i: usize) -> Option<&str> {
        self.positional.get(i).map(String::as_str)
    }

    /// Whether the flag is given (`-r`, `--all`).
    pub fn has(&self, flag: &str) -> bool {
        self.flags.iter().any(|(f, _)| f.eq_ignore_ascii_case(flag))
    }

    /// A flag's value (`-n 5` → `5`).
    pub fn value(&self, flag: &str) -> Option<&str> {
        self.flags.iter().find(|(f, _)| f.eq_ignore_ascii_case(flag)).and_then(|(_, v)| v.as_deref())
    }
}
