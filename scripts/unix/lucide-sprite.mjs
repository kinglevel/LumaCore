#!/usr/bin/env node
// Builds crates/ui/lumacore-webui/web/vendor/lucide/sprite.svg from the icon
// names in icons.txt plus LumaCore's own glyphs (kit/glyphs.svg), as one
// <symbol id="i-<name>"> per icon (decisions §30: Lucide, one sprite, only
// the icons we use). Usage:
//   npm pack lucide-static@<version>   (into an empty folder, then unpack)
//   node scripts/unix/lucide-sprite.mjs <path to unpacked package/>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const pkg = process.argv[2];
if (!pkg) { console.error('usage: lucide-sprite.mjs <lucide-static package dir>'); process.exit(2); }
const vendor = join(repo, 'crates/ui/lumacore-webui/web/vendor/lucide');
const names = readFileSync(join(vendor, 'icons.txt'), 'utf8').split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#'));
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;

const symbols = names.map(name => {
  const svg = readFileSync(join(pkg, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .split('\n').map(l => l.trim()).filter(Boolean).join('');
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});
const own = readFileSync(join(repo, 'crates/ui/lumacore-webui/web/kit/glyphs.svg'), 'utf8')
  .match(/<symbol[\s\S]*?<\/symbol>/g) || [];

writeFileSync(join(vendor, 'sprite.svg'),
  `<!-- lucide-static ${version} (ISC, lucide.LICENSE) + LumaCore glyphs; generated by scripts/unix/lucide-sprite.mjs -->\n`
  + `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${[...symbols, ...own].join('\n')}\n</svg>\n`);
console.log(`sprite.svg: ${symbols.length} Lucide + ${own.length} own icons (lucide-static ${version})`);
